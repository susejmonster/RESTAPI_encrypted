-- 1. Create Departments Table
CREATE TABLE IF NOT EXISTS Departments (
    DepartmentID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DepartmentName VARCHAR(50)
);

-- 2. Create Roles Table (Optional, since you mentioned it earlier)
CREATE TABLE IF NOT EXISTS Roles (
    RolesID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RolesName VARCHAR(50)
);

DROP TABLE IF EXISTS Employees;
-- 3. Create Employees Table
CREATE TABLE IF NOT EXISTS Employees (
    EmployeeID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName VARCHAR(50),
    LastName VARCHAR(50),
    DateOfBirth DATE,
    Gender VARCHAR(10) CHECK (Gender IN ('Male', 'Female')),
    DepartmentID INT,
    Salary DECIMAL(10, 2),
    HireDate DATE,
    FOREIGN KEY (DepartmentID) REFERENCES Departments (DepartmentID)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);



