-- 1. Create Transaction Categories Table
CREATE TABLE TransactionCategories (
    CategoryID SERIAL PRIMARY KEY,
    CategoryName VARCHAR(50) NOT NULL,
    CategoryType VARCHAR(20) NOT NULL CHECK (CategoryType IN ('Income', 'Expense', 'Bonus', 'Reimbursement', 'Deduction')),
    Description TEXT
);

-- 2. Create Transactions Table linked to Employees
CREATE TABLE Transactions (
    TransactionID SERIAL PRIMARY KEY,
    EmployeeID INT NOT NULL,
    CategoryID INT NOT NULL,
    Amount NUMERIC(10, 2) NOT NULL,
    TransactionDate DATE DEFAULT CURRENT_DATE,
    Description TEXT,
    CONSTRAINT fk_employee FOREIGN KEY (EmployeeID) REFERENCES Employees(EmployeeID) ON DELETE CASCADE,
    CONSTRAINT fk_category FOREIGN KEY (CategoryID) REFERENCES TransactionCategories(CategoryID) ON DELETE RESTRICT
);


